-- Execute este script no SQL Editor do Supabase.
create table if not exists public.membership_interest (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  full_name text not null,
  email text,
  phone text not null,
  city text,
  cultural_area text not null,
  consent boolean not null default false
);

alter table public.membership_interest enable row level security;

-- Permite que visitantes enviem uma manifestação de interesse.
-- Não permite que visitantes leiam os dados enviados.
create policy "Public can submit membership interest"
on public.membership_interest
for insert
to anon
with check (consent = true);

